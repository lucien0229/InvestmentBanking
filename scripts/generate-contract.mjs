import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const input = JSON.parse(fs.readFileSync(path.join(root, "contracts/openapi.json"), "utf8"));
const output = `// Generated by scripts/generate-contract.mjs. Do not edit.\nexport const openApiContract = ${JSON.stringify(input, null, 2)} as const;\n`;
fs.mkdirSync(path.join(root, "packages/contracts/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "packages/contracts/generated/openapi.ts"), output);
